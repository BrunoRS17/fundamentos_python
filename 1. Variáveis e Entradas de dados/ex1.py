"""Faça um programa que peça dois números inteiros. Imprima a
soma desses dois números na tela"""


#Solicita os dos números
numero1 = int(input("Digite um número inteiro: "))
numero2 = int(input("Digite um segundo número inteiro: "))

#Realiza a soma
soma = numero1 + numero2

#Exibe o resultado
print("\nO resultado é:")
print(f"{numero1} + {numero2} = {soma}")